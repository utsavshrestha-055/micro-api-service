"""Generate async gRPC client stubs from the pinned protobuf contracts."""

from pathlib import Path

from grpc_tools import protoc

ROOT = Path(__file__).resolve().parents[1]
PROTO_DIR = ROOT / "proto"
OUTPUT_DIR = ROOT / "app" / "generated"


def main() -> None:
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    result = protoc.main(
        [
            "grpc_tools.protoc",
            f"-I{PROTO_DIR}",
            f"--python_out={OUTPUT_DIR}",
            f"--grpc_python_out={OUTPUT_DIR}",
            *(str(PROTO_DIR / name) for name in ("auth.proto", "catalog.proto", "orders.proto")),
        ]
    )
    if result:
        raise SystemExit(result)
    for module in ("auth", "catalog", "orders"):
        grpc_stub = OUTPUT_DIR / f"{module}_pb2_grpc.py"
        contents = grpc_stub.read_text()
        contents = contents.replace(
            f"import {module}_pb2 as {module}__pb2",
            f"from app.generated import {module}_pb2 as {module}__pb2",
        )
        grpc_stub.write_text(
            contents.replace(
                "# Generated by the gRPC Python protocol compiler plugin. DO NOT EDIT!",
                "# Generated by the gRPC Python protocol compiler plugin. DO NOT EDIT!\n"
                "# mypy: ignore-errors",
                1,
            )
        )
        protobuf_module = OUTPUT_DIR / f"{module}_pb2.py"
        protobuf_contents = protobuf_module.read_text()
        protobuf_module.write_text(
            protobuf_contents.replace(
                "# Generated by the protocol buffer compiler.  DO NOT EDIT!",
                "# Generated by the protocol buffer compiler.  DO NOT EDIT!\n# mypy: ignore-errors",
                1,
            )
        )


if __name__ == "__main__":
    main()
